def make_window(idx, x0, y0, rng, mask_gene=0.25, mask_dapi=True):
    c = xyz[idx] - np.array([x0, y0, 0], np.float32)
    gc = np.floor(c / GRID).astype(np.int64); gc[:, 2] = np.floor((xyz[idx, 2] - 8.0) / GRID)
    # unique voxels: bump colliding molecules along z (rank within each run of equal keys; vectorised, same result as the loop)
    key = gc[:, 0] * 10**8 + gc[:, 1] * 10**4 + gc[:, 2]
    o = np.argsort(key, kind="stable"); k = key[o]
    pos = np.arange(len(k)); start = np.maximum.accumulate(np.where(np.r_[True, k[1:] != k[:-1]], pos, 0))
    gc[o, 2] += pos - start
    for _ in range(100):   # a bump can land on an occupied voxel (only with coarse grids; never at 0.1 um): bump again until unique
        _, first, cnt = np.unique(gc, axis=0, return_index=True, return_counts=True)
        if (cnt == 1).all(): break
        dup = np.ones(len(gc), bool); dup[first] = False; gc[dup, 2] += 1
    g = gene[idx]; gm = rng.random(len(idx)) < mask_gene
    g_in = g.copy(); g_in[gm] = G
    b = dict(coord=torch.tensor(c), grid=torch.tensor(gc), g=torch.tensor(g), g_in=torch.tensor(g_in), gmask=torch.tensor(gm),
             coord_n=torch.tensor(np.c_[c[:, :2] / WIN - 0.5, (xyz[idx, 2:3] - 16.0) / 5.0], dtype=torch.float32))
    if D:
        d = dapi[idx].copy(); dm = np.zeros(len(idx), bool)
        if mask_dapi:   # blank DAPI in 3 um disks around ~1 seed per 400 um^2
            seeds = c[rng.random(len(idx)) < (WIN * WIN / 400) / max(len(idx), 1), :2]
            if len(seeds):
                from scipy.spatial import cKDTree
                dm = cKDTree(seeds).query(c[:, :2], k=1)[0] < 3.0
        d_in = d.copy(); d_in[dm] = 0
        b.update(dapi=torch.tensor(d), dapi_in=torch.tensor(d_in), dmask=torch.tensor(dm.astype(np.float32)))
    return b

def collate(ws):
    out = {k: torch.cat([w[k] for w in ws]) for k in ws[0]}
    out["offset"] = torch.tensor(np.cumsum([len(w["g"]) for w in ws]))
    return {k: v.to(DEV, non_blocking=True) for k, v in out.items()}

def windows_in(xmin, xmax, rng, n):
    res = []
    for _ in range(n):
        x0 = rng.uniform(xmin, xmax - WIN); y0 = rng.uniform(0, 750 - WIN)
        idx = np.flatnonzero((xyz[:, 0] >= x0) & (xyz[:, 0] < x0 + WIN) & (xyz[:, 1] >= y0) & (xyz[:, 1] < y0 + WIN))
        res.append((idx, x0, y0))
    return res

def train_batch(rng):
    return collate([make_window(i, x0, y0, rng) for i, x0, y0 in windows_in(0, XSPLIT, rng, a.nwin)])

def bn_recalibrate(net, rng):
    """PTv3 BN momentum is 0.01: reset running stats and re-estimate them on 40 training batches. (Utonia has no BN: nothing to do.)"""
    if not any(isinstance(mod, nn.BatchNorm1d) for mod in net.modules()): net.eval(); return
    for mod in net.modules():
        if isinstance(mod, nn.BatchNorm1d): mod.reset_running_stats(); mod.momentum = None
    net.train()
