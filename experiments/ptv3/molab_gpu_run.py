@app.cell
def _(HF_PUSH, HF_MODEL_REPO, HF_TOKEN, LOG_IMAGES, RUNDIR, TRACKIO, TRACKIO_PROJECT, TRACKIO_PUBLISH_MIN, TRACKIO_SPACE, mo, os, shutil, time):
    # ---- Trackio live dashboard. Everything here is best effort: the first failure (or a missing token) prints one warning and
    # turns tracking off; training and checkpoints never depend on it. Each run is logged from this kernel by reading the run's
    # train_log.tsv, so train.py itself does not import Trackio.
    import threading as _th, math as _math, collections as _co

    class Tracker:
        LR, LR_WARMUP = 2e-3, 100          # train.py defaults (--lr, warm-up steps); the notebook does not override them

        def __init__(self, on, project, space, token, images):
            self.project, self.space, self.run, self.on, self.images = project, space or None, None, False, images
            self.img_sec = []   # seconds spent per image set (read + 3 plots + log), reported at the end of each run
            self.url = f"https://huggingface.co/spaces/{space}" if space else None
            self.pub_t, self.pub_th = 0.0, None
            if not on: print("Trackio: off (TRACKIO_TOGGLE / BENTO_TRACKIO)"); return
            if self.space and not token:
                print("WARNING: Trackio disabled: no HF token (paste one in the box above, then re-run). Training is unaffected."); return
            if token: os.environ["HF_TOKEN"] = token   # Trackio and huggingface_hub read the token from here; it is never printed
            self.dir, self.snap = RUNDIR / "trackio", RUNDIR / "trackio_hf"   # live database + media / consistent copy pushed to HF
            os.environ["TRACKIO_DIR"] = str(self.dir)   # read when trackio is first imported
            try:
                import trackio; self.trackio = trackio; self.on = True
            except Exception as e:
                print(f"WARNING: Trackio disabled: import failed ({type(e).__name__}: {e}). Training is unaffected.")

        def _off(self, why):
            if self.on: print(f"WARNING: Trackio disabled ({why}). Training is unaffected; metrics are still in train_log.tsv and on HF.", flush=True)
            self.on, self.run = False, None

        @staticmethod
        def _timed(fn, timeout):
            # run a possibly-networked Trackio call in a thread so a slow or stuck Space (or a login prompt) cannot stall the matrix
            box = {}
            def go():
                try: box["v"] = fn()
                except BaseException as e: box["e"] = e
            t = _th.Thread(target=go, daemon=True); t.start(); t.join(timeout)
            if t.is_alive(): raise TimeoutError(f"no answer in {timeout} s")
            if "e" in box: raise box["e"]
            return box.get("v")

        def start(self, name, group, config, total_steps):
            # resume="allow": a run with this name continues (same run, global steps) in a new session; its last step is read from the Space
            self.run, self.total = None, total_steps
            if not self.on: return
            try:
                self.run = self._timed(lambda: self.trackio.init(
                    project=self.project, name=name, group=group, space_id=None,   # local database; published to the Space by publish()
                    config=config, resume="allow", embed=False, auto_log_gpu=False, auto_log_cpu=False), 300)
                self.next = int(getattr(self.run, "_next_step", 0) or 0)   # steps below this are already on the dashboard
                self.win = _co.deque(maxlen=5); self.img_step, self.img_mt = self.next - 1, None
                print(f"Trackio: run {name} ({'resumed at step ' + str(self.next) if self.next else 'new'})", flush=True)
            except Exception as e: self._off(f"init {name}: {type(e).__name__}: {e}")

        def log(self, metrics, step):
            if not (self.on and self.run): return
            try:
                m = {k: float(v) for k, v in metrics.items() if isinstance(v, (int, float)) and not isinstance(v, bool) and _math.isfinite(v)}
                if m: self.run.log(m, step=int(step)); self.next = max(self.next, int(step) + 1)
            except Exception as e: self._off(f"log: {type(e).__name__}: {e}")

        def log_images(self, npz):
            # train.py --preview-every writes runs/<run>/preview.npz (CPU arrays, <= 20k molecules of one fixed held-out window).
            # Here: 3 small Agg PNGs (600 px wide, dpi 80) -> trackio.Image, at the preview's step. Any failure turns images off only.
            if not (self.images and self.on and self.run) or not npz.exists(): return
            try:
                _mt = npz.stat().st_mtime
                if _mt == self.img_mt: return   # unchanged since the last poll
                self.img_mt = _mt
                import numpy as np
                import matplotlib
                from matplotlib.figure import Figure
                from matplotlib.patches import Patch
                from matplotlib.backends.backend_agg import FigureCanvasAgg
                from sklearn.decomposition import PCA
                _t = time.time()
                with np.load(npz, allow_pickle=True) as z: P = {k: z[k] for k in z.files}
                step = int(P["step"])
                if step <= self.img_step: return
                g, pr, xy, names = P["gene"].astype(int), P["pred"].astype(int), P["xy"], P["genes"]
                def png(fig):
                    c = FigureCanvasAgg(fig); c.draw(); return np.asarray(c.buffer_rgba())[..., :3].copy()
                top = np.bincount(g, minlength=len(names)).argsort()[::-1]          # fixed window, so a fixed gene order
                cmap = [tuple(c) for c in matplotlib.colormaps["tab20"](np.arange(12))[:, :3]]
                def col(v):
                    out = np.full((len(v), 3), 0.82)
                    for i, gi in enumerate(top[:12]): out[v == gi] = cmap[i]
                    return out
                fig = Figure(figsize=(7.5, 3.9), dpi=80); ax = fig.subplots(1, 2, sharey=True)
                for a_, v, ttl in [(ax[0], g, "true gene"), (ax[1], pr, f"predicted (own gene masked), top-1 {100 * (pr == g).mean():.1f}%")]:
                    a_.scatter(xy[:, 0], xy[:, 1], c=col(v), s=1.2, lw=0, rasterized=True); a_.set_title(ttl, fontsize=9); a_.set_aspect("equal"); a_.tick_params(labelsize=6)
                fig.legend(handles=[Patch(color=cmap[i], label=str(names[top[i]])) for i in range(12)] + [Patch(color=(0.82,) * 3, label="other")], loc="lower center", ncol=7, fontsize=6, frameon=False)
                fig.subplots_adjust(bottom=0.2, top=0.9, wspace=0.05); fig.suptitle(f"held-out window x 1080-1180, y 325-425 um, step {step}", fontsize=9)
                im_win = png(fig)
                e = PCA(2, random_state=0).fit_transform(P["emb"].astype(np.float32)); e *= np.sign(e[np.abs(e).argmax(0), [0, 1]])   # fixed sign
                fig = Figure(figsize=(7.5, 4.5), dpi=80); a_ = fig.subplots()
                for lab, key, c in [("unassigned", -1, "#bbbbbb"), ("cytoplasm", 0, "#ff7f0e"), ("nucleus", 1, "#1f77b4")]:
                    m = P["nuc"] == key; a_.scatter(e[m, 0], e[m, 1], s=1.5, lw=0, c=c, alpha=.6, label=f"{lab} ({m.sum()})", rasterized=True)
                a_.legend(fontsize=7, markerscale=5); a_.set(xlabel="PC1", ylabel="PC2"); a_.set_title(f"context embedding, PCA, step {step}", fontsize=9); a_.tick_params(labelsize=6)
                im_pca = png(fig)
                t20 = top[:20]; C = np.zeros((20, 20))
                ri, ci = np.full(len(names), -1), np.full(len(names), -1); ri[t20] = ci[t20] = np.arange(20)
                ok = (ri[g] >= 0) & (ci[pr] >= 0); np.add.at(C, (ri[g][ok], ci[pr][ok]), 1)
                C /= np.maximum([(g == gi).sum() for gi in t20], 1)[:, None]   # row = all molecules of that true gene
                fig = Figure(figsize=(7.5, 6.6), dpi=80); a_ = fig.subplots(); im = a_.imshow(C, cmap="viridis", vmin=0, vmax=max(C.max(), 1e-6))
                a_.set_xticks(range(20)); a_.set_xticklabels([str(names[i]) for i in t20], rotation=90, fontsize=6)
                a_.set_yticks(range(20)); a_.set_yticklabels([str(names[i]) for i in t20], fontsize=6)
                a_.set(xlabel="predicted", ylabel="true"); a_.set_title(f"top-20 genes, row-normalised (fraction of all true), step {step}", fontsize=9); fig.colorbar(im, ax=a_, shrink=.8)
                fig.tight_layout(); im_cm = png(fig)
                T = self.trackio
                self.run.log({"img/window_true_vs_pred": T.Image(im_win), "img/embedding_pca": T.Image(im_pca), "img/confusion_top20": T.Image(im_cm),
                              "preview/top1_window": float((pr == g).mean())}, step=step)
                self.img_step = step; self.img_sec.append(time.time() - _t)
            except Exception as e:
                print(f"WARNING: Trackio images disabled ({type(e).__name__}: {e}); scalars continue.", flush=True); self.images = False

        def lr_at(self, step):   # train.py's schedule: linear warm-up, then cosine to 0 over --steps
            return self.LR * min(1, (step + 1) / self.LR_WARMUP) * 0.5 * (1 + _math.cos(_math.pi * min(1, step / self.total)))

        def follow(self, tsv):   # tsv = runs/<run>/train_log.tsv; images come from runs/<run>/preview.npz
            # called every few seconds while train.py runs: log new train_log.tsv rows (step sec loss_gene loss_dapi acc_masked).
            # Rows below self.next are skipped, so the steps replayed after a checkpoint resume are not logged twice.
            def poll():
                if not (self.on and self.run): return
                self.log_images(tsv.parent / "preview.npz")
                if not tsv.exists(): return
                try: lines = tsv.read_text().split("\n")[1:-1]   # drop the header and a possibly half-written last line
                except Exception: return
                for line in lines:
                    f = line.split("\t")
                    if len(f) != 5 or not f[0].isdigit(): continue
                    step, sec = int(f[0]), float(f[1])
                    if step < self.next: continue
                    self.win.append((step, sec)); (s0, t0), (s1, t1) = self.win[0], self.win[-1]
                    m = dict(loss_gene=float(f[2]), loss_dapi=float(f[3]), acc_masked=float(f[4]), lr=self.lr_at(step), elapsed_min=sec / 60)
                    if s1 > s0: m["s_per_step"] = (t1 - t0) / (s1 - s0)   # over the last ~100 steps (sec is logged in whole seconds)
                    self.log({f"train/{k}": v for k, v in m.items()}, step)
                self.publish()
            return poll

        def _has_rows(self):
            try:
                import sqlite3
                _db = self.dir / f"{self.project}.db"
                if not _db.exists(): return False
                _c = sqlite3.connect(f"file:{_db}?mode=ro", uri=True)
                try: return _c.execute("SELECT EXISTS(SELECT 1 FROM metrics)").fetchone()[0] == 1
                finally: _c.close()
            except Exception: return False

        def publish(self, force=False, wait=0):
            # re-publish the whole project to the static Space in a background thread (never blocks the poll loop); throttled.
            # A failure turns publishing off (one warning); local logging and the HF-repo copy carry on.
            if not (self.on and self.space) or (self.pub_th is not None and self.pub_th.is_alive()): return
            if not force and time.time() - self.pub_t < TRACKIO_PUBLISH_MIN * 60: return
            if not self._has_rows(): return   # Trackio writes its database a moment after the first log: skip this cycle, retry next poll
            self.pub_t = time.time()
            def go():
                try: self.trackio.sync(project=self.project, space_id=self.space, sdk="static", force=True)
                except FileNotFoundError as e:   # database not there yet (race with Trackio's writer): try again next cycle
                    print(f"Trackio publish skipped this cycle ({e})", flush=True); self.pub_t = 0.0
                except Exception as e:
                    print(f"WARNING: Trackio publishing to {self.space} disabled ({type(e).__name__}: {e}). Logging continues locally.", flush=True)
                    self.space = None
            self.pub_th = _th.Thread(target=go, daemon=True); self.pub_th.start()
            if wait: self.pub_th.join(wait)

        def snapshot(self):
            # consistent copy of the Trackio database (sqlite backup API, safe while it is being written) + images, for the HF push
            if not self.on: return
            try:
                import sqlite3
                self.snap.mkdir(parents=True, exist_ok=True)
                for db in self.dir.glob("*.db"):   # single-file copy: journal_mode=delete and closed, so no rows are left in a -wal file
                    tmp = self.snap / (db.name + ".tmp"); tmp.unlink(missing_ok=True)
                    s, d = sqlite3.connect(db), sqlite3.connect(tmp)
                    try: s.backup(d); d.execute("PRAGMA journal_mode=DELETE")
                    finally: d.close(); s.close()
                    os.replace(tmp, self.snap / db.name)
                if (self.dir / "media").exists(): shutil.copytree(self.dir / "media", self.snap / "media", dirs_exist_ok=True)
            except Exception as e: print(f"Trackio snapshot skipped ({type(e).__name__}: {e})", flush=True)

        def restore(self, src):
            # new session: start from the database pushed by the last one, so resume="allow" continues the same runs
            if not self.on or not (src / f"{self.project}.db").exists() or (self.dir / f"{self.project}.db").exists(): return
            try:
                self.dir.mkdir(parents=True, exist_ok=True); shutil.copy2(src / f"{self.project}.db", self.dir / f"{self.project}.db")
                if (src / "media").exists(): shutil.copytree(src / "media", self.dir / "media", dirs_exist_ok=True)
                print(f"Trackio: restored project {self.project} from HF", flush=True)
            except Exception as e: self._off(f"restore: {type(e).__name__}: {e}")

        def finish(self):
            if self.img_sec: print(f"Trackio images: {len(self.img_sec)} sets, {sum(self.img_sec) / len(self.img_sec):.2f} s each (max {max(self.img_sec):.2f})", flush=True)
            self.img_sec = []
            if self.on and self.run:
                try: self._timed(self.run.finish, 180)
                except Exception as e: self._off(f"finish: {type(e).__name__}: {e}")
            self.run = None
            self.publish(force=True, wait=300)   # the run's final numbers on the dashboard

    TRK = Tracker(TRACKIO, TRACKIO_PROJECT, TRACKIO_SPACE, HF_TOKEN, LOG_IMAGES)
    _view = (f"hf download {HF_MODEL_REPO} --include '{RUNDIR.name}/trackio_hf/*' --local-dir bento3_runs && "
             f"TRACKIO_DIR=bento3_runs/{RUNDIR.name}/trackio_hf uvx trackio show --project {TRACKIO_PROJECT}")
    if TRK.on and TRK.url: print("Trackio dashboard (public, updated every", TRACKIO_PUBLISH_MIN, "min):", TRK.url, "| project", TRACKIO_PROJECT)
