def ward(Fn, w=None):
    """Connectivity-constrained Ward with molecule-count weights. sklearn's ward_tree blew past 5 GB here (chained clusters
    with thousands of neighbours pile up stale heap entries), so this is a small heap-with-lazy-deletion version."""
    import heapq
    t = time.time(); w = cnt.astype(float) if w is None else w
    C = np.zeros((2 * N - 1, Fn.shape[1])); C[:N] = Fn; n = np.zeros(2 * N - 1); n[:N] = w
    alive = np.zeros(2 * N - 1, bool); alive[:N] = True
    nb = [set(A.indices[A.indptr[i]:A.indptr[i + 1]]) - {i} for i in range(N)] + [None] * (N - 1)
    def dist(a, bs):
        bs = np.fromiter(bs, int); d = np.sqrt(2 * n[a] * n[bs] / (n[a] + n[bs]) * ((C[bs] - C[a]) ** 2).sum(1)); return bs, d
    heap = []
    for i in range(N):
        bs, d = dist(i, [j for j in nb[i] if j > i]) if any(j > i for j in nb[i]) else (np.array([], int), np.array([]))
        heap += list(zip(d.tolist(), [i] * len(bs), bs.tolist()))
    heapq.heapify(heap); children = []; heights = []; m = N
    while heap:
        d, a, b = heapq.heappop(heap)
        if not (alive[a] and alive[b]): continue
        alive[a] = alive[b] = False; alive[m] = True; n[m] = n[a] + n[b]; C[m] = (n[a] * C[a] + n[b] * C[b]) / n[m]
        s_ = (nb[a] | nb[b]) - {a, b}; nb[m] = s_; nb[a] = nb[b] = None
        for c in s_: nb[c].discard(a); nb[c].discard(b); nb[c].add(m)
        if s_:
            bs, dd = dist(m, s_)
            for x, y in zip(dd.tolist(), bs.tolist()): heapq.heappush(heap, (x, m, y))
        children.append((a, b)); heights.append(d); m += 1
        if len(heap) > 8_000_000: heap = [e for e in heap if alive[e[1]] and alive[e[2]]]; heapq.heapify(heap)
    rest = list(np.flatnonzero(alive[:m]))
    while len(rest) > 1:     # disconnected pieces (rare): finish with unconstrained Ward among them
        R = np.array(rest); best = None
        for i in range(len(R)):
            bs, d = dist(R[i], R[i + 1:]) if i + 1 < len(R) else (None, None)
            if bs is not None and (best is None or d.min() < best[0]): best = (d.min(), R[i], bs[d.argmin()])
        d, a, b = best; alive[a] = alive[b] = False; alive[m] = True; n[m] = n[a] + n[b]; C[m] = (n[a] * C[a] + n[b] * C[b]) / n[m]
        children.append((a, b)); heights.append(d); rest = [r for r in rest if r not in (a, b)] + [m]; m += 1
    return np.array(children), np.maximum.accumulate(np.array(heights)), time.time() - t

