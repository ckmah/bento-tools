class UtoniaNet(nn.Module):
    """Gene + DAPI features -> new input linear -> Utonia-small encoder -> every level mapped back to the molecules and concatenated
    (Utonia's own 'upcast', 36+72+144+288+432 = 972 channels) -> LayerNorm + linear to 48 -> our heads. No learned decoder."""
    def __init__(s):
        super().__init__()
        from utoniamodel.model import PointTransformerV3 as UtoniaPTv3
        s.emb = nn.Embedding(G + 1, 32)
        s.bb = UtoniaPTv3(in_channels=32 + D + (1 if D else 0) + 3, enable_flash=False, drop_path=0.1, mask_token=False, **UTONIA_SMALL)
        s.neck = nn.Sequential(nn.LayerNorm(sum(UTONIA_SMALL["enc_channels"])), nn.Linear(sum(UTONIA_SMALL["enc_channels"]), 48))
        s.gene_head = nn.Linear(48, G); s.dapi_head = nn.Linear(48, D) if D else None
    def forward(s, batch):
        f = [s.emb(batch["g_in"])]
        if D: f += [batch["dapi_in"], batch["dmask"][:, None]]
        f += [batch["coord_n"]]
        p = s.bb(dict(coord=batch["coord"] * U_SCALE, grid_coord=batch["grid"], feat=torch.cat(f, 1), offset=batch["offset"],
                      grid_size=GRID * U_SCALE))
        while "pooling_parent" in p.keys():
            parent = p.pop("pooling_parent"); inv = p.pop("pooling_inverse")
            parent.feat = torch.cat([parent.feat, p.feat[inv]], -1); p = parent
        return s.neck(p.feat).float()

