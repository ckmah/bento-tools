def strip_tiles(HALO=15.0):
    """Tile the held-out strip (x > 950 um) with halo windows; yields (sel, core, x0, y0)."""
    have = np.zeros(len(xyz), bool)
    for x0 in np.arange(XSPLIT, 1230, WIN - 2 * HALO):
        for y0 in np.arange(-HALO, 750, WIN - 2 * HALO):
            sel = np.flatnonzero((xyz[:, 0] >= max(x0 - HALO, XSPLIT)) & (xyz[:, 0] < x0 + WIN - HALO) & (xyz[:, 1] >= y0) & (xyz[:, 1] < y0 + WIN))
            if len(sel) < 50: continue
            core = (xyz[sel, 0] >= x0 + (0 if x0 == XSPLIT else HALO)) & (xyz[sel, 0] < x0 + WIN - HALO) & (xyz[sel, 1] >= y0 + HALO) & (xyz[sel, 1] < y0 + WIN - HALO)
            core &= ~have[sel]
            yield sel, core, x0 - HALO, y0
            have[sel[core]] = True
    strip_tiles.have = have

